import test from 'node:test';
import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
const url=new URL(process.env.DATABASE_URL||'postgresql://invalid/invalid');
if(!['localhost','127.0.0.1'].includes(url.hostname)||url.port!=='5432'||url.pathname!=='/hardware_pos_ci')throw Error('Refusing financial test outside isolated CI database');
const {pool,initDbTables,addCustomerCreditPayment,insertSupplierPayment,insertSupplier}=await import('../backend/db.ts');
const {initFinancialAccounts,createFinancialAccount,registerFinancialOpeningBalance,listFinancialAccounts,recordFinancialTransfer,registerCustomerCheque,transitionCustomerCheque,listCustomerCheques,recordFinancialReconciliation,listFinancialReconciliations,listFinancialMovements,recordPaidExpense,assignRepresentativeAccount,linkRepresentativeLogin,resolveRepresentativeFinancialIdentity,requestCashHandover,decideCashHandover}=await import('../backend/financialAccounts.ts');

test('financial accounts, collections, handovers, cheque clearance, reconciliation and statements on real PostgreSQL',async()=>{
  const shopId='finance-ci-'+randomUUID(),otherShop='finance-other-'+randomUUID();
  const id=()=>randomUUID(),recordedBy='CI manager',day='2026-11-24',customerId=id();
  const cash=id(),bank=id(),rep=id(),foreign=id();
  const balances=async()=>Object.fromEntries((await listFinancialAccounts(pool,shopId)).map(a=>[a.id,a.balance]));
  const debt=async()=>Number((await pool.query('SELECT credit_balance FROM customers WHERE id=$1',[customerId])).rows[0].credit_balance);
  try{
    await initDbTables();await initFinancialAccounts(pool);
    for(const [accountId,name,kind,scope] of [[cash,'Office','Office Cash',shopId],[bank,'Bank','Bank',shopId],[rep,'Representative','Representative Cash',shopId],[foreign,'Foreign bank','Bank',otherShop]])await createFinancialAccount(pool,{id:accountId,shopId:scope,name,kind,recordedBy});
    await pool.query("INSERT INTO customers(id,shop_id,name,loyalty_balance,purchase_count,credit_limit,credit_balance) VALUES($1,$2,'Finance CI customer',0,0,10000,1000)",[customerId,shopId]);
    await registerFinancialOpeningBalance(pool,{id:id(),shopId,accountId:cash,amount:200,effectiveDate:day,recordedBy});
    await assert.rejects(registerFinancialOpeningBalance(pool,{id:id(),shopId,accountId:cash,amount:100,effectiveDate:day,recordedBy}),/no recorded movements/);
    const payment={id:'cpay-'+id(),shopId,customerId,customerName:'Finance CI customer',amount:150,date:day,paymentMethod:'Cash',createdBy:recordedBy};
    await assert.rejects(addCustomerCreditPayment(payment,true,foreign),/active financial account/);
    assert.equal(await debt(),1000);
    await addCustomerCreditPayment(payment,true,rep);
    await addCustomerCreditPayment(payment,true,rep);
    assert.equal(await debt(),850);assert.equal((await balances())[rep],150);
    const transfer={requestId:id(),shopId,fromAccountId:rep,toAccountId:cash,amount:100,effectiveDate:day,recordedBy,note:'CI physical cash counted',handover:true,currentBusinessDate:day};
    await recordFinancialTransfer(pool,transfer);
    assert.equal((await recordFinancialTransfer(pool,{...transfer,currentBusinessDate:'2026-11-25'})).replayed,true);
    await assert.rejects(recordFinancialTransfer(pool,{...transfer,requestId:id(),amount:60}),/Insufficient/);
    await assert.rejects(recordFinancialTransfer(pool,{...transfer,requestId:id(),toAccountId:foreign,handover:false}),/two active/);
    assert.deepEqual(await balances(),{[cash]:300,[bank]:0,[rep]:50});
    const cheque={id:'cheque-'+id(),shopId,customerId,chequeNumber:'CI-001',issuingBank:'CI Bank',drawerName:'CI Customer',amount:300,receivedDate:day,dueDate:'2026-11-25',recordedBy};
    await registerCustomerCheque(pool,cheque);
    assert.equal((await registerCustomerCheque(pool,cheque)).replayed,true);
    await assert.rejects(registerCustomerCheque(pool,{...cheque,id:id(),chequeNumber:'CI-002',amount:600}),/Pending cheques/);
    const deposit={shopId,chequeId:cheque.id,eventId:id(),nextStatus:'Deposited',effectiveDate:'2026-11-25',recordedBy,depositAccountId:bank};
    await assert.rejects(transitionCustomerCheque(pool,{...deposit,effectiveDate:day}),/before its due date/);
    await transitionCustomerCheque(pool,deposit);
    assert.equal(await debt(),850);assert.equal((await balances())[bank],0);
    const clearing={id:'cpay-cheque-'+cheque.id,shopId,customerId,customerName:'Finance CI customer',amount:300,date:'2026-11-25',paymentMethod:'Cheque',createdBy:recordedBy,note:'CI cheque clearance'};
    const event={chequeId:cheque.id,eventId:id(),recordedBy};
    await assert.rejects(addCustomerCreditPayment({...clearing,amount:301},true,bank,event),/do not match/);
    await addCustomerCreditPayment(clearing,true,bank,event);
    await addCustomerCreditPayment(clearing,true,bank,event);
    assert.equal(await debt(),550);assert.equal((await balances())[bank],300);
    assert.equal((await listCustomerCheques(pool,shopId)).find(c=>c.id===cheque.id).status,'Cleared');
    await assert.rejects(transitionCustomerCheque(pool,{shopId,chequeId:cheque.id,eventId:id(),nextStatus:'Bounced',effectiveDate:'2026-11-25',recordedBy,note:'Invalid after clearance'}),/Invalid cheque status transition/);
    const bounced={...cheque,id:'cheque-'+id(),chequeNumber:'CI-003',amount:100};
    await registerCustomerCheque(pool,bounced);
    await transitionCustomerCheque(pool,{...deposit,chequeId:bounced.id,eventId:id()});
    await transitionCustomerCheque(pool,{shopId,chequeId:bounced.id,eventId:id(),nextStatus:'Bounced',effectiveDate:'2026-11-25',recordedBy,note:'Bank returned unpaid'});
    assert.equal(await debt(),550);assert.equal((await balances())[bank],300);
    const check={id:id(),shopId,accountId:cash,effectiveDate:day,currentBusinessDate:day,observedAmount:295,reference:'CI count',recordedBy};
    await assert.rejects(recordFinancialReconciliation(pool,check),/Explain the discrepancy/);
    const saved=await recordFinancialReconciliation(pool,{...check,note:'CI shortage'});
    assert.equal(saved.expectedAmount,300);assert.equal(saved.variance,-5);
    assert.equal((await recordFinancialReconciliation(pool,{...check,note:'CI shortage'})).replayed,true);
    assert.equal((await listFinancialReconciliations(pool,shopId)).length,1);
    assert.equal((await balances())[cash],300);
    const statement=await listFinancialMovements(pool,{shopId,accountId:cash,fromDate:day,toDate:day,offset:1,limit:1});
    assert.equal(statement.total,2);assert.equal(statement.opening,0);assert.equal(statement.inflows,300);assert.equal(statement.outflows,0);assert.equal(statement.closing,300);assert.equal(statement.rows[0].runningBalance,300);
    await assert.rejects(listFinancialMovements(pool,{shopId,accountId:foreign,fromDate:day,toDate:day,offset:0,limit:10}),/not found/);
    const supplierId=id();
    await insertSupplier({id:supplierId,shopId,name:'CI supplier',companyName:'CI supplier',phone:'',email:'',address:'',taxNumber:''});
    const supplierPayment={id:'spay-'+id(),shopId,supplierId,supplierName:'CI supplier',amount:100,date:'2026-11-25',paymentMethod:'Bank Transfer',createdBy:recordedBy};
    await assert.rejects(insertSupplierPayment(supplierPayment,foreign),/matching the payment method/);
    await assert.rejects(insertSupplierPayment({...supplierPayment,amount:301},bank),/Insufficient/);
    assert.equal(Number((await pool.query('SELECT COUNT(*) AS n FROM supplier_payments WHERE id=$1',[supplierPayment.id])).rows[0].n),0);
    await insertSupplierPayment(supplierPayment,bank);
    await insertSupplierPayment(supplierPayment,bank);
    await assert.rejects(insertSupplierPayment({...supplierPayment,amount:101},bank),/identifier already used/);
    assert.equal((await balances())[bank],200);
    const expense={id:'exp-'+id(),shopId,desc:'CI delivery fuel',category:'Vehicle fuel',amount:40,date:day,recordedBy,role:'Store Manager',sourceAccountId:cash,paymentMethod:'Cash'};
    await assert.rejects(recordPaidExpense(pool,{...expense,sourceAccountId:foreign}),/matching the payment method/);
    await assert.rejects(recordPaidExpense(pool,{...expense,amount:301}),/Insufficient/);
    assert.equal(Number((await pool.query('SELECT COUNT(*) AS n FROM manual_expenses WHERE id=$1',[expense.id])).rows[0].n),0);
    await recordPaidExpense(pool,expense);
    assert.equal((await recordPaidExpense(pool,{...expense,date:'2026-11-25'})).replayed,true);
    await assert.rejects(recordPaidExpense(pool,{...expense,amount:41}),/identifier already used/);
    await assert.rejects(recordPaidExpense(pool,{...expense,paymentMethod:'Bank Transfer'}),/identifier already used/);
    assert.equal((await balances())[cash],260);
    const expenseRow=(await pool.query('SELECT shop_id,amount FROM manual_expenses WHERE id=$1',[expense.id])).rows[0];
    assert.equal(expenseRow.shop_id,shopId);assert.equal(Number(expenseRow.amount),40);
    const after=await listFinancialMovements(pool,{shopId,accountId:cash,fromDate:day,toDate:day,offset:0,limit:100});
    assert.equal(after.outflows,40);assert.equal(after.closing,260);
    const legacyId='legacy-exp-'+id();
    await pool.query("INSERT INTO manual_expenses(id,description,amount,date,category) VALUES($1,'Legacy CI',10,$2,'Other')",[legacyId,day]);
    await initDbTables();
    assert.equal((await pool.query('SELECT shop_id FROM manual_expenses WHERE id=$1',[legacyId])).rows[0].shop_id,null);
    // Independent representative identity and cash custody fixtures.
    const employee=id(),repUser=id(),managerUser=id(),repCash=id();
    await pool.query("INSERT INTO employees(id,shop_id,name,role,salary,attendance_status,performance_score) VALUES($1,$2,'CI Representative','Cashier',0,'Present',0)",[employee,shopId]);
    await pool.query("INSERT INTO users(id,email,name,role,password_hash) VALUES($1,$2,'CI Representative','Cashier','test-only'),($3,$4,'CI Manager','Store Manager','test-only')",[repUser,repUser+'@example.invalid',managerUser,managerUser+'@example.invalid']);
    await createFinancialAccount(pool,{id:repCash,shopId,name:'CI assigned cash',kind:'Representative Cash',recordedBy});
    await assert.rejects(assignRepresentativeAccount(pool,{shopId:otherShop,employeeId:employee,accountId:repCash,recordedBy}),/registered sales representative/);
    await assignRepresentativeAccount(pool,{shopId,employeeId:employee,accountId:repCash,recordedBy});
    await assert.rejects(linkRepresentativeLogin(pool,{shopId,employeeId:employee,userId:managerUser,recordedBy}),/existing sales representative login/);
    await linkRepresentativeLogin(pool,{shopId,employeeId:employee,userId:repUser,recordedBy});
    assert.equal((await resolveRepresentativeFinancialIdentity(pool,shopId,repUser)).accountId,repCash);
    assert.equal(await resolveRepresentativeFinancialIdentity(pool,otherShop,repUser),null);
    const ownPayment={...payment,id:'cpay-'+id(),amount:100,createdBy:'CI Representative'};
    await assert.rejects(addCustomerCreditPayment(ownPayment,true,rep,undefined,{userId:repUser}),/authorization changed/);
    await addCustomerCreditPayment(ownPayment,true,repCash,undefined,{userId:repUser});
    await addCustomerCreditPayment(ownPayment,true,repCash,undefined,{userId:repUser});
    assert.equal((await balances())[repCash],100);
    assert.equal(await debt(),450);
    const request={id:id(),shopId,userId:repUser,toAccountId:cash,amount:70,note:'Counted cash'};
    const race=await Promise.allSettled([requestCashHandover(pool,request),requestCashHandover(pool,{...request,id:id()})]);
    assert.equal(race.filter(r=>r.status==='fulfilled').length,1);
    const winner=race.find(r=>r.status==='fulfilled').value.id;
    assert.equal((await requestCashHandover(pool,{...request,id:winner})).replayed,true);
    assert.equal((await balances())[repCash],100);
    await assert.rejects(recordFinancialTransfer(pool,{...transfer,requestId:id(),fromAccountId:repCash,amount:31}),/Insufficient/);
    const decision={id:winner,shopId,decision:'Confirmed',managerUserId:managerUser,recordedBy,effectiveDate:day,note:'Cash received'};
    await assert.rejects(decideCashHandover(pool,{...decision,shopId:otherShop}),/not found/);
    await assert.rejects(decideCashHandover(pool,{...decision,managerUserId:repUser}),/Manager authorization/);
    const approvals=await Promise.all([decideCashHandover(pool,decision),decideCashHandover(pool,decision)]);
    assert.deepEqual(approvals.map(r=>r.replayed).sort(),[false,true]);
    assert.equal((await balances())[repCash],30);assert.equal((await balances())[cash],330);
    const rejected={...request,id:id(),amount:20};
    await requestCashHandover(pool,rejected);
    await assert.rejects(decideCashHandover(pool,{...decision,id:rejected.id,decision:'Rejected',note:''}),/Invalid handover decision/);
    await decideCashHandover(pool,{...decision,id:rejected.id,decision:'Rejected',note:'Cash not received'});
    assert.equal((await balances())[repCash],30);assert.equal((await balances())[cash],330);
    await assert.rejects(decideCashHandover(pool,{...decision,id:rejected.id}),/already decided/);
    const retryAfterRejection={...request,id:id(),amount:30};
    await requestCashHandover(pool,retryAfterRejection);
    assert.equal((await balances())[repCash],30);
    // Account-level receipts must remain visible as unallocated, never silently assigned to invoices.
    const {receivableAging}=await import('../backend/receivableAging.ts');
    const aging=await receivableAging(pool,shopId);
    const account=aging.customers.find(c=>c.id===customerId);
    assert.equal(account.recorded_balance,450);
    assert.equal(account.invoice_balance,0);
    assert.equal(account.unallocated_payments,550);
    assert.equal(account.difference,450);
    assert.equal(aging.needsReview,1);
    const paymentRows=await pool.query('SELECT id,amount FROM customer_credit_payments WHERE shop_id=$1 AND customer_id=$2',[shopId,customerId]);
    assert.equal(paymentRows.rowCount,3);
    assert.equal(paymentRows.rows.reduce((sum,row)=>sum+Number(row.amount),0),550);
    assert.equal((await listCustomerCheques(pool,shopId)).find(c=>c.id===bounced.id).status,'Bounced');
    assert.equal((await receivableAging(pool,otherShop)).customers.some(c=>c.id===customerId),false);
    // Supplier aging: fully received orders only; advances and partial receipts remain visible.
    const {supplierPayableAging,registerSupplierDueDate}=await import('../backend/payableAging.ts');
    const poIds={received:id(),partial:id(),ordered:id(),cancelled:id(),unknown:id(),paid:id()};
    for(const [name,status,total] of [['received','Received',500],['partial','Partially Received',700],['ordered','Ordered',900],['cancelled','Cancelled',1000],['unknown','Received',80],['paid','Received',50]]){
      await pool.query('INSERT INTO purchase_orders(id,shop_id,po_number,date,supplier_id,supplier_name,total,status) VALUES($1,$2,$3,$4,$5,$6,$7,$8)',[poIds[name],shopId,'CI-PO-'+poIds[name],day,supplierId,'CI supplier',total,status]);
    }
    const terms={shopId,purchaseOrderId:poIds.received,dueDate:'2099-12-31',evidence:'CI supplier agreement',recordedBy};
    await assert.rejects(registerSupplierDueDate(pool,{...terms,shopId:otherShop}),/not found in this shop/);
    await assert.rejects(registerSupplierDueDate(pool,{...terms,purchaseOrderId:poIds.partial}),/Only received/);
    await assert.rejects(registerSupplierDueDate(pool,{...terms,dueDate:'2000-01-01'}),/cannot precede/);
    const termResults=await Promise.all([registerSupplierDueDate(pool,terms),registerSupplierDueDate(pool,terms)]);
    assert.deepEqual(termResults.map(r=>r.replayed).sort(),[false,true]);
    await assert.rejects(registerSupplierDueDate(pool,{...terms,evidence:'Changed agreement'}),/already registered/);
    for(const [name,amount] of [['received',100],['ordered',20],['paid',50]]){
      const linked={...supplierPayment,id:'spay-'+id(),purchaseOrderId:poIds[name],amount};
      await insertSupplierPayment(linked,bank);
      await insertSupplierPayment(linked,bank);
    }
    const payables=await supplierPayableAging(pool,shopId);
    const byId=Object.fromEntries(payables.orders.map(o=>[o.id,o]));
    assert.equal(payables.estimatedPayable,480);
    assert.equal(byId[poIds.received].outstanding,400);
    assert.equal(byId[poIds.received].bucket,'Not overdue');
    assert.equal(byId[poIds.unknown].bucket,'No due date');
    assert.equal(byId[poIds.partial].outstanding,null);
    assert.equal(byId[poIds.ordered].bucket,'Review');
    assert.equal(byId[poIds.cancelled],undefined);
    assert.equal(byId[poIds.paid],undefined);
    assert.equal(payables.unmatchedPayments.length,1);
    assert.equal(payables.unmatchedPayments[0].paid,100);
    assert.equal(payables.needsReview,3);
    assert.equal((await supplierPayableAging(pool,otherShop)).estimatedPayable,0);
    const {recordPositionBalance,listPositionRegisters}=await import('../backend/positionRegisters.ts');
    const snapshot={id:id(),shopId,reference:'CI-VEHICLE',kind:'Fixed asset',label:'Delivery vehicle',amount:1000,effectiveDate:'2020-01-01',evidence:'CI asset valuation',recordedBy};
    const registered=await Promise.all([recordPositionBalance(pool,snapshot),recordPositionBalance(pool,snapshot)]);
    assert.deepEqual(registered.map(r=>r.replayed).sort(),[false,true]);
    await assert.rejects(recordPositionBalance(pool,{...snapshot,amount:1001}),/identifier already used/);
    await assert.rejects(recordPositionBalance(pool,{...snapshot,id:id()}),/already exists/);
    await assert.rejects(recordPositionBalance(pool,{...snapshot,id:id(),amount:-1}),/Valid evidenced/);
    await assert.rejects(recordPositionBalance(pool,{...snapshot,id:id(),effectiveDate:'2099-12-31'}),/Future carrying balances/);
    await recordPositionBalance(pool,{...snapshot,id:id(),amount:900,effectiveDate:'2020-01-02'});
    await recordPositionBalance(pool,{...snapshot,id:id(),reference:'CI-LOAN',kind:'Loan liability',label:'Loan',amount:200});
    await recordPositionBalance(pool,{...snapshot,id:id(),reference:'CI-TAX',kind:'Tax liability',label:'Verified zero tax',amount:0});
    await recordPositionBalance(pool,{...snapshot,id:id(),reference:'CI-LOSS',kind:'Retained earnings',label:'Recorded loss',amount:-50});
    const registerRows=await listPositionRegisters(pool,shopId);
    assert.equal(registerRows.length,4);
    assert.equal(registerRows.find(r=>r.reference==='CI-VEHICLE').amount,900);
    assert.equal(registerRows.find(r=>r.reference==='CI-TAX').amount,0);
    assert.equal(registerRows.find(r=>r.reference==='CI-LOSS').amount,-50);
    assert.equal((await listPositionRegisters(pool,otherShop)).length,0);
    assert.equal((await pool.query('SELECT id FROM ars_position_register WHERE shop_id=$1 AND reference=$2',[shopId,snapshot.reference])).rowCount,2);
    assert.equal((await balances())[bank],30);
    // Deliberately retain isolated fixtures for subsequent full-row pg_dump/pg_restore verification.
  }finally{await pool.end();}
});
