import test from 'node:test';
import assert from 'node:assert/strict';
import {spawnSync} from 'node:child_process';

test('purchase orders, delivery notes and GRNs preserve scoped saved quantities and safe document content',()=>{
 const script = `
 import assert from 'node:assert/strict';
 import {purchaseOrderDocument} from './src/utils/purchaseOrderDocument.ts';
 import {buildDeliveryNoteHtml} from './src/utils/deliveryNote.ts';
 import {buildGrnHtml} from './src/utils/grnDocument.ts';
 const settings={storeName:'ARS Distributor',activeShopId:'shop-a',taxRate:0,currency:'LKR',invoicePrefix:'ARS'};
 const po={shopId:'shop-a',poNumber:'PO/123',date:'2026-11-25',supplierName:'Supplier A',status:'Partially Received',total:250,items:[{productName:'Lock',sellingUnitLabel:'Box',baseUnitsPerPurchaseUnit:10,quantity:2,costPrice:125}]};
 const report=purchaseOrderDocument(po,'shop-a');
 assert.deepEqual(report.rows,[[1,'Lock','Box',10,2,125,250]]);
 assert.equal(report.filename,'ars-po-PO-123');
 assert.throws(()=>purchaseOrderDocument(po,'shop-b'),/active shop/);
 assert.throws(()=>purchaseOrderDocument({...po,items:[{...po.items[0],quantity:-1}]},'shop-a'),/Invalid purchase order line/);
 const tx={shopId:'shop-a',status:'Completed',invoiceNumber:'INV-1',date:'2026-11-25',customerName:'<script>bad()</script>',cashierName:'INTERNAL-OPERATOR',total:987654.32,items:[{productName:'Lock & handle',sellingUnitLabel:'Box',quantity:2,sellingPrice:493827.16,costPrice:123456.78},{productName:'Bolt',sellingUnitLabel:'Piece',quantity:3}]};
 const dn=buildDeliveryNoteHtml(tx,settings,'');
 assert.ok(dn.includes('A4 portrait'));
 assert.ok(dn.includes('&lt;script&gt;bad()&lt;/script&gt;'));
 assert.ok(!dn.includes('<script>bad()'));
 assert.ok(dn.includes('<td>Lock &amp; handle</td><td>Box</td><td>2</td><td></td>'));
 assert.ok(dn.includes('<td>Bolt</td><td>Piece</td><td>3</td><td></td>'));
 for(const secret of ['987654.32','493827.16','123456.78','INTERNAL-OPERATOR'])assert.ok(!dn.includes(secret));
 assert.ok(dn.includes('Powered by RS Nextward'));
 assert.throws(()=>buildDeliveryNoteHtml({...tx,status:'Refunded'},settings,''),/completed invoice/);
 assert.throws(()=>buildDeliveryNoteHtml({...tx,shopId:'shop-b'},settings,''),/active shop/);
 const grn={id:'grn-a',shopId:'shop-a',po_number:'PO/123',supplier_name:'Supplier A',received_by:'Warehouse',created_at:'2026-11-25T20:00:00Z',note:'<img onerror=bad()>',recorded_count:2,company:{name:'ARS Distributor',address:'Test address',phone:''},items:[{productName:'Lock',unit:'Box',quantity:2,baseUnitsPerUnit:10},{productName:'Bolt',unit:'Piece',quantity:3,baseUnitsPerUnit:1}]};
 const html=buildGrnHtml(grn,'shop-a','grn-a');
 assert.ok(html.includes('<td>Lock</td><td>Box</td><td>2</td><td>20</td>'));
 assert.ok(html.includes('<td>Bolt</td><td>Piece</td><td>3</td><td>3</td>'));
 assert.ok(html.includes('&lt;img onerror=bad()&gt;'));
 assert.ok(!html.includes('<img onerror=bad()>'));
 assert.ok(html.includes('Powered by RS Nextward'));
 assert.throws(()=>buildGrnHtml(grn,'shop-b','grn-a'),/Invalid receiving document/);
 assert.throws(()=>buildGrnHtml(grn,'shop-a','grn-b'),/Invalid receiving document/);
 assert.throws(()=>buildGrnHtml({...grn,recorded_count:3},'shop-a','grn-a'),/Invalid receiving document/);
 assert.throws(()=>buildGrnHtml({...grn,items:[{...grn.items[0],baseUnitsPerUnit:0},grn.items[1]]},'shop-a','grn-a'),/Invalid unit conversion/);
 `;
 const result=spawnSync(process.execPath,['--import','tsx','--input-type=module','-e',script],{encoding:'utf8',timeout:60000});
 assert.equal(result.status,0,result.stderr||result.stdout||String(result.error));
});
